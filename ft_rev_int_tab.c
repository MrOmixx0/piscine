void	ft_rev_int_tab(int	*tab, int size)
{
	int	s;
	int	f;
	int	l;

	f = 0;
	l = size - 1;
	while (f < l)
	{
		s = tab[f];
		tab[f] = tab[l];
		tab [l] = s;
		l--;
		f++;
	}
}
